import { submitFeedback } from '../controllers/feedback.controller';
import { supportMessages, sendSupportMessage } from '../controllers/support.controller';
import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { requireAuth } from '../middleware/auth.middleware';
import { listWishlist, saveWishlist, removeWishlist, wishlistState, wishlistStates } from '../controllers/wishlist.controller';
import { createNeed, listNeeds, setNeedOpen } from '../controllers/need.controller';
import { listConversations, startConversation, listMessages, sendMessage, unreadConversations, setConversationImportant } from '../controllers/conversation.controller';
const router = Router();
router.use(requireAuth);
const writes = rateLimit({ windowMs: 60000, limit: 60 });
router.post('/feedback', rateLimit({ windowMs: 60 * 60 * 1000, limit: 20 }), submitFeedback);
router.get('/support/messages', supportMessages);
router.post('/support/messages', writes, sendSupportMessage);
router.get('/wishlist', listWishlist);
router.get('/wishlist/states', wishlistStates);
router.get('/wishlist/listings/:listingId', wishlistState);
router.put('/wishlist/listings/:listingId', writes, saveWishlist);
router.delete('/wishlist/:entryId', writes, removeWishlist);
router.get('/needs', listNeeds);
router.post('/needs', rateLimit({ windowMs: 60 * 60 * 1000, limit: 20 }), createNeed);
router.patch('/needs/:needId', writes, setNeedOpen);
router.get('/conversations', listConversations);
router.get('/conversations/unread', unreadConversations);
router.post('/conversations', writes, startConversation);
router.patch('/conversations/:conversationId/important', writes, setConversationImportant);
router.get('/conversations/:conversationId/messages', listMessages);
router.post('/conversations/:conversationId/messages', writes, sendMessage);
export default router;
